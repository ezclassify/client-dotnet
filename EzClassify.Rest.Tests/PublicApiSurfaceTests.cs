using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Runtime.CompilerServices;
using System.Text;
using Xunit;

namespace EzClassify.Tests;

/// <summary>
/// 1.0 public-surface freeze gate.
///
/// Reflects over the two shipped assemblies (Contract and Client), renders every public and protected type and member in a stable
/// sorted text form, and diffs the result against the committed golden file
/// EzClassify.Rest.Tests/PublicApiSurface.golden.txt.
///
/// The public API locked at 1.0. Any change to it (adding, removing, or
/// renaming a public type or member, or changing a signature) fails this test
/// until the golden is regenerated as a deliberate, reviewed act:
///
///   make api-surface
///
/// then commit the updated golden together with the API change.
/// </summary>
public class PublicApiSurfaceTests
{
    private const string GoldenRelativePath = "PublicApiSurface.golden.txt";

    // One representative type per shipped assembly; the reflection walk covers
    // the whole assembly each type lives in.
    private static readonly Type[] AssemblyAnchors =
    {
        typeof(EzClassify.ResultParser),           // EzClassify.Rest.Contract
        typeof(EzClassify.EzClassifyClient),       // EzClassify.Rest.Client
    };

    [Fact]
    public void PublicSurface_MatchesCommittedGolden()
    {
        var actual = RenderSurface();
        var goldenPath = Path.Combine(
            FindRepoRoot(), "EzClassify.Rest.Tests", GoldenRelativePath);

        if (Environment.GetEnvironmentVariable("UPDATE_API_SURFACE") == "1")
        {
            File.WriteAllText(goldenPath, actual);
            return;
        }

        Assert.True(File.Exists(goldenPath),
            $"Missing golden file {goldenPath}. Run 'make api-surface' to create it.");

        // Normalize line endings so a git checkout with autocrlf cannot fail the gate.
        var expected = File.ReadAllText(goldenPath).Replace("\r\n", "\n");

        if (expected == actual) return;

        var expectedLines = expected.Split('\n');
        var actualLines = actual.Split('\n');
        var removed = expectedLines.Except(actualLines).ToList();
        var added = actualLines.Except(expectedLines).ToList();

        var msg = new StringBuilder();
        msg.AppendLine("Public API surface changed. This SDK's public API is a 1.0-locked contract;");
        msg.AppendLine("any change must be reviewed deliberately, not shipped as a side effect.");
        msg.AppendLine();
        if (removed.Count > 0)
        {
            msg.AppendLine($"Removed from surface ({removed.Count} line(s)):");
            foreach (var line in removed.Take(40)) msg.AppendLine("  - " + line);
            if (removed.Count > 40) msg.AppendLine($"  ... and {removed.Count - 40} more");
            msg.AppendLine();
        }
        if (added.Count > 0)
        {
            msg.AppendLine($"Added to surface ({added.Count} line(s)):");
            foreach (var line in added.Take(40)) msg.AppendLine("  + " + line);
            if (added.Count > 40) msg.AppendLine($"  ... and {added.Count - 40} more");
            msg.AppendLine();
        }
        if (removed.Count == 0 && added.Count == 0)
        {
            msg.AppendLine("(No line-level additions or removals; lines were reordered or reformatted.)");
            msg.AppendLine();
        }
        msg.AppendLine("If this change was intentional and has been reviewed, regenerate the golden:");
        msg.AppendLine("  make api-surface");
        msg.AppendLine("and commit EzClassify.Rest.Tests/PublicApiSurface.golden.txt with your change.");

        Assert.Fail(msg.ToString());
    }

    private static string FindRepoRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir != null)
        {
            if (File.Exists(Path.Combine(dir.FullName, "EzClassify.Rest.sln")))
                return dir.FullName;
            dir = dir.Parent;
        }
        throw new DirectoryNotFoundException("Cannot locate EzClassify.Rest.sln");
    }

    // ---- surface rendering -------------------------------------------------

    private static string RenderSurface()
    {
        var sb = new StringBuilder();
        sb.AppendLine("# EzClassify .NET SDK public API surface. 1.0-locked contract.");
        sb.AppendLine("# Generated by PublicApiSurfaceTests; do not edit by hand.");
        sb.AppendLine("# Regenerate deliberately with: make api-surface");

        var assemblies = AssemblyAnchors
            .Select(t => t.Assembly)
            .Distinct()
            .OrderBy(a => a.GetName().Name, StringComparer.Ordinal);

        foreach (var assembly in assemblies)
        {
            sb.AppendLine();
            sb.AppendLine($"== {assembly.GetName().Name} ==");

            var types = assembly.GetTypes()
                .Where(IsSurfaceType)
                .OrderBy(t => t.FullName, StringComparer.Ordinal);

            foreach (var type in types)
            {
                sb.AppendLine();
                sb.AppendLine(RenderTypeHeader(type));
                foreach (var line in RenderMembers(type))
                    sb.AppendLine("  " + line);
            }
        }
        return sb.ToString();
    }

    private static bool IsSurfaceType(Type t)
    {
        if (t.IsDefined(typeof(CompilerGeneratedAttribute), inherit: false)) return false;
        if (t.Name.Contains('<')) return false;
        return t.IsPublic || t.IsNestedPublic || t.IsNestedFamily || t.IsNestedFamORAssem;
    }

    private static string RenderTypeHeader(Type t)
    {
        string kind;
        var mods = new List<string>();
        if (t.IsEnum) kind = "enum";
        else if (t.IsInterface) kind = "interface";
        else if (t.IsValueType) kind = "struct";
        else if (typeof(Delegate).IsAssignableFrom(t)) kind = "delegate";
        else
        {
            kind = "class";
            if (t.IsAbstract && t.IsSealed) mods.Add("static");
            else if (t.IsAbstract) mods.Add("abstract");
            else if (t.IsSealed) mods.Add("sealed");
        }

        var bases = new List<string>();
        if (kind == "class" && t.BaseType != null && t.BaseType != typeof(object))
            bases.Add(RenderType(t.BaseType));
        if (kind is "class" or "struct" or "interface")
            bases.AddRange(t.GetInterfaces()
                .Where(i => i.IsPublic || i.IsNestedPublic)
                .Select(RenderType)
                .OrderBy(n => n, StringComparer.Ordinal));

        var header = kind + " "
            + (mods.Count > 0 ? string.Join(" ", mods) + " " : "")
            + RenderTypeName(t);
        if (t.IsEnum && Enum.GetUnderlyingType(t) != typeof(int))
            header += " : " + RenderType(Enum.GetUnderlyingType(t));
        else if (bases.Count > 0)
            header += " : " + string.Join(", ", bases);
        return header;
    }

    private static IEnumerable<string> RenderMembers(Type t)
    {
        if (t.IsEnum)
        {
            var underlying = Enum.GetUnderlyingType(t);
            return t.GetFields(BindingFlags.Public | BindingFlags.Static)
                .Select(f => (name: f.Name,
                    value: Convert.ToString(Convert.ChangeType(f.GetRawConstantValue(), underlying),
                        CultureInfo.InvariantCulture)))
                .OrderBy(m => m.value, StringComparer.Ordinal)
                .ThenBy(m => m.name, StringComparer.Ordinal)
                .Select(m => $"{m.name} = {m.value}");
        }

        const BindingFlags flags = BindingFlags.Public | BindingFlags.NonPublic
            | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly;
        var lines = new List<(int rank, string line)>();

        foreach (var c in t.GetConstructors(flags).Where(c => IsVisible(c) && !IsCompilerNoise(c)))
            lines.Add((0, $"ctor {Visibility(c)} .ctor({RenderParams(c.GetParameters())})"));

        foreach (var m in t.GetMethods(flags).Where(m => IsVisible(m) && !IsCompilerNoise(m)))
        {
            if (m.IsSpecialName && (m.Name.StartsWith("get_") || m.Name.StartsWith("set_")
                || m.Name.StartsWith("add_") || m.Name.StartsWith("remove_")))
                continue; // rendered with their property/event
            var generic = m.IsGenericMethodDefinition
                ? "<" + string.Join(", ", m.GetGenericArguments().Select(a => a.Name)) + ">"
                : "";
            lines.Add((1, $"method {Visibility(m)}{MethodMods(m, t)} {RenderType(m.ReturnType)} "
                + $"{m.Name}{generic}({RenderParams(m.GetParameters())})"));
        }

        foreach (var p in t.GetProperties(flags))
        {
            // Auto-property accessors are compiler-generated but the property is
            // hand-authored surface, so only true record synthesis is skipped here.
            if (p.Name == "EqualityContract" || p.Name.Contains('<')) continue;
            var accessors = new List<(string kw, MethodInfo m)>();
            if (p.GetMethod != null && IsVisible(p.GetMethod)) accessors.Add(("get", p.GetMethod));
            if (p.SetMethod != null && IsVisible(p.SetMethod))
                accessors.Add((IsInitOnly(p.SetMethod) ? "init" : "set", p.SetMethod));
            if (accessors.Count == 0) continue;
            var mostVisible = accessors.Any(a => a.m.IsPublic) ? "public" : "protected";
            var rendered = accessors.Select(a =>
            {
                var v = a.m.IsPublic ? "public" : "protected";
                return v == mostVisible ? a.kw + ";" : v + " " + a.kw + ";";
            });
            var name = p.GetIndexParameters().Length > 0
                ? $"this[{RenderParams(p.GetIndexParameters())}]"
                : p.Name;
            var anyAccessor = accessors[0].m;
            lines.Add((2, $"property {mostVisible}{MethodMods(anyAccessor, t)} {RenderType(p.PropertyType)} "
                + $"{name} {{ {string.Join(" ", rendered)} }}"));
        }

        foreach (var e in t.GetEvents(flags))
        {
            var add = e.AddMethod;
            if (add == null || !IsVisible(add) || IsCompilerNoise(add)) continue;
            lines.Add((3, $"event {Visibility(add)}{MethodMods(add, t)} "
                + $"{RenderType(e.EventHandlerType!)} {e.Name}"));
        }

        foreach (var f in t.GetFields(flags).Where(f => IsVisible(f) && !f.IsSpecialName))
        {
            if (f.IsLiteral)
                lines.Add((4, $"const {Visibility(f)} {RenderType(f.FieldType)} {f.Name} "
                    + $"= {RenderConstant(f.GetRawConstantValue())}"));
            else
            {
                var mods = (f.IsStatic ? " static" : "") + (f.IsInitOnly ? " readonly" : "");
                lines.Add((4, $"field {Visibility(f)}{mods} {RenderType(f.FieldType)} {f.Name}"));
            }
        }

        return lines
            .OrderBy(l => l.rank)
            .ThenBy(l => l.line, StringComparer.Ordinal)
            .Select(l => l.line);
    }

    private static bool IsVisible(MethodBase m) => m.IsPublic || m.IsFamily || m.IsFamilyOrAssembly;
    private static bool IsVisible(FieldInfo f) => f.IsPublic || f.IsFamily || f.IsFamilyOrAssembly;

    private static string Visibility(MethodBase m) => m.IsPublic ? "public" : "protected";
    private static string Visibility(FieldInfo f) => f.IsPublic ? "public" : "protected";

    // Record synthesis (Clone, PrintMembers, EqualityContract, equality members)
    // derives entirely from the positional property list, which the dump already
    // captures. Skipping it keeps the golden focused on hand-authored surface.
    private static bool IsCompilerNoise(MethodBase m) =>
        m.Name.Contains('<')
        || m.IsDefined(typeof(CompilerGeneratedAttribute), inherit: false);

    private static string MethodMods(MethodBase m, Type declaring)
    {
        if (declaring.IsInterface) return m.IsStatic ? " static" : "";
        var mods = "";
        if (m.IsStatic) mods += " static";
        if (m.IsAbstract) mods += " abstract";
        else if (m.IsVirtual && !m.IsFinal) mods += " virtual";
        return mods;
    }

    private static bool IsInitOnly(MethodInfo setter) =>
        setter.ReturnParameter.GetRequiredCustomModifiers()
            .Any(mod => mod.Name == "IsExternalInit");

    private static string RenderParams(ParameterInfo[] parameters) =>
        string.Join(", ", parameters.Select(p =>
        {
            var prefix = p.ParameterType.IsByRef ? (p.IsOut ? "out " : "ref ") : "";
            if (p.IsDefined(typeof(ParamArrayAttribute), inherit: false)) prefix = "params ";
            var suffix = p.HasDefaultValue ? " = " + RenderDefault(p) : "";
            return $"{prefix}{RenderType(p.ParameterType)} {p.Name}{suffix}";
        }));

    private static string RenderDefault(ParameterInfo p)
    {
        var v = p.RawDefaultValue;
        if (v == null)
            return p.ParameterType.IsValueType
                && Nullable.GetUnderlyingType(p.ParameterType) == null
                ? "default" : "null";
        return RenderConstant(v);
    }

    private static string RenderConstant(object? value) => value switch
    {
        null => "null",
        string s => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"",
        bool b => b ? "true" : "false",
        char c => "'" + c + "'",
        _ => Convert.ToString(value, CultureInfo.InvariantCulture) ?? "null",
    };

    // Full name for the type's own header line: generic parameters by name.
    private static string RenderTypeName(Type t)
    {
        var name = t.FullName ?? t.Name;
        name = name.Replace('+', '.');
        if (!t.IsGenericTypeDefinition) return name;
        name = name[..name.IndexOf('`')];
        return name + "<" + string.Join(", ", t.GetGenericArguments().Select(a => a.Name)) + ">";
    }

    private static string RenderType(Type t)
    {
        if (t.IsByRef) return RenderType(t.GetElementType()!);
        if (t.IsArray) return RenderType(t.GetElementType()!) + "[]";
        if (t.IsGenericParameter) return t.Name;
        if (Nullable.GetUnderlyingType(t) is { } underlying)
            return RenderType(underlying) + "?";
        if (t.IsGenericType)
        {
            var def = t.GetGenericTypeDefinition();
            var name = def.FullName ?? def.Name;
            name = name.Replace('+', '.');
            name = name[..name.IndexOf('`')];
            var args = string.Join(", ", t.GetGenericArguments().Select(RenderType));
            return name + "<" + args + ">";
        }
        return (t.FullName ?? t.Name).Replace('+', '.');
    }
}
