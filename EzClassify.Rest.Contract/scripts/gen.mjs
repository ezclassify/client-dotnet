#!/usr/bin/env node
/**
 * Generates the complete public wire-model surface from the vendored
 * @ezclassify contract. JSON Schemas drive the engine values; the
 * canonical OpenAPI contract gates the document, Context-envelope, wire-enum,
 * and low-level operation templates emitted alongside them.
 *
 * Usage:
 *   node scripts/gen.mjs <schemas-dir> <openapi-file> <output-file> [--check]
 *
 * Produces the schema-driven Models.g.cs records and four template-driven
 * .g.cs files containing Context/document records and extensible wire enums.
 * Complex sub-types the client does not deep-parse (guide-rule match trees,
 * engine snapshots, and the like) are mapped to `System.Text.Json.JsonElement`,
 * the idiomatic .NET type for opaque wire JSON carried through untouched, and
 * nullable only when the member is optional.
 *
 * Build-time only, no runtime dependencies added to the integration.
 */

import fs from 'fs';
import path from 'path';
import { createHash } from 'crypto';
import { fileURLToPath } from 'url';

const [schemasDir, openapiFile, outputFile, mode] = process.argv.slice(2);

if (!schemasDir || !openapiFile || !outputFile || (mode && mode !== '--check')) {
  console.error('Usage: node scripts/gen.mjs <schemas-dir> <openapi-file> <output-file> [--check]');
  process.exit(1);
}

if (!fs.existsSync(openapiFile)) {
  throw new Error(`OpenAPI contract not found: ${openapiFile}`);
}

const openapiText = fs.readFileSync(openapiFile, 'utf8');
const OPENAPI_COMPONENTS = [
  'ArtifactReference', 'ContextResolution', 'DocumentResponseProjection',
  'DocumentAuditReport', 'DocumentAccessAssessment',
  'ContextDocumentAuditResult', 'ContextDocumentAccessAssessmentResult',
  'ContextSchemeProcessResult', 'ContextGuideEvaluationResult',
  'ContextAccessDecisionResult', 'AccessRequirementsDescription',
];
for (const component of OPENAPI_COMPONENTS) {
  if (!new RegExp(`^    ${component}:`, 'm').test(openapiText)) {
    throw new Error(`Canonical OpenAPI component is missing: ${component}`);
  }
}

/**
 * C# type for an opaque JSON payload the client carries through without
 * deep-parsing. JsonElement is strongly typed, has real equality and
 * serialization semantics, and rejects arbitrary CLR objects a caller might
 * pass by mistake, the correct idiom over a bare object.
 */
const OPAQUE_JSON = 'JsonElement?';

/** Opaque JSON for a member: a value is always present when the contract requires one. */
function opaque(isRequired) {
  return isRequired ? 'JsonElement' : OPAQUE_JSON;
}

/** Convert camelCase or kebab-case to PascalCase. */
function toPascalCase(name) {
  return name
    .split(/[-_]/)
    .map(s => s.charAt(0).toUpperCase() + s.slice(1))
    .join('');
}

/**
 * Opaque complex types the client does not deep-parse.
 * They appear as System.Text.Json.JsonElement? in generated records.
 */
const OPAQUE = new Set([
  'TraceEntry',
  'GuideMatchSpec', 'GuideRuleOutcome', 'RuleCondition',
  'RuleWhen', 'RuleWhenNode',
]);

