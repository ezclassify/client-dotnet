/**
 * Types this script does not emit from a JSON Schema but may reference by name
 * when a generated record $refs one of them. They are declared in the
 * templates under scripts/templates, which this script emits alongside the
 * schema-driven records. The generator cannot express them proportionally (the
 * typed FixAction on Fix and Change; typed ConceptRef references; the trace
 * sub-records; the fact-or-output union inside RenderAssessment), but a $ref
 * from a generated record (e.g. ProcessResult.appliedFixes -> Change) must
 * still resolve to the real C# type, not opaque JSON.
 */
const HAND_WRITTEN = new Set([
  'Fix', 'Change', 'ConceptRef', 'ExplanationTrace', 'GuideBreakdownEntry',
  'AccessRuleActivation', 'AccessComparisonResult', 'RuleReference',
  'SourceReference', 'Notice', 'RenderAssessment',
]);

/**
 * Schema definition names whose C# equivalent already ships under a different
 * name. The contract calls the collected-notice shape CollectedNotice; this SDK
 * names the identical record Notice, and the two are field-for-field the same.
 * Aliasing keeps one typed notice record on the public surface instead of
 * introducing a second name for the same wire object.
 */
const REF_ALIASES = {
  CollectedNotice: 'Notice',
};

/** Resolve a JSON Schema $ref to a C# type name. */
function resolveRef(ref) {
  const raw = ref.replace('#/definitions/', '');
  const decoded = decodeURIComponent(raw);
  if (decoded === 'RenderResultsByFormat') {
    return 'IReadOnlyDictionary<string, RenderResult>';
  }
  if (decoded === 'SuggestResultsByCategory') {
    return 'IReadOnlyDictionary<string, SuggestResult>';
  }
  if (decoded === 'Record<string,string>' || decoded === 'AggregatedMarkings') {
    return 'IReadOnlyDictionary<string, string>';
  }
  const name = REF_ALIASES[decoded] ?? decoded;
  if (name.includes('<') || name.includes('%')) return OPAQUE_JSON;
  if (OPAQUE.has(name)) return OPAQUE_JSON;
  if (GENERATED.has(name)) return name;
  if (HAND_WRITTEN.has(name)) return name;
  return OPAQUE_JSON;
}

// Wire enums that surface on generated record fields as typed values instead of
// raw strings. Keyed by "ClassName.fieldName" so a field name that is a wire enum
// on one type is unaffected on another type where the same name is opaque. The
// types are extensible structs over the raw token, declared in the
// WireEnums.g.cs.tmpl template; response parsers wrap whatever token arrives and
// requests send it back through ToWire().
const ENUM_FIELDS = {
  'Assertion.confidence': 'Confidence',
  'ValidationError.severity': 'Severity',
  'Warning.kind': 'WarningKind',
  'ScanMatch.role': 'StructuralRole',
  'RecognitionCorrection.reason': 'RecognitionCorrectionReason',
  'RecognitionResult.status': 'RecognitionStatus',
  'RecognitionResult.role': 'StructuralRole',
  'RecognitionWithCorrections.status': 'RecognitionStatus',
  'RecognitionWithCorrections.role': 'StructuralRole',
  'ScanLimits.status': 'ScanStatus',
  'ScanLimits.limitHit': 'RecognitionLimit',
};

/**
 * Map a JSON Schema property descriptor to a C# type string.
 *
 * @param {object} propSchema - JSON Schema for this property.
 * @param {boolean} isRequired - Whether this field is required in the parent schema.
 * @param {string} [enumKey] - "ClassName.fieldName" for wire-enum lookup.
 */
function mapType(propSchema, isRequired, enumKey) {
  if (!propSchema) return opaque(isRequired);

  if (enumKey && ENUM_FIELDS[enumKey] && (propSchema.enum || propSchema.$ref)) {
    const enumType = ENUM_FIELDS[enumKey];
    return isRequired ? enumType : enumType + '?';
  }

  if (propSchema.$ref) {
    const resolved = resolveRef(propSchema.$ref);
    if (resolved === OPAQUE_JSON) return opaque(isRequired);
    return isRequired ? resolved : resolved + '?';
  }

  const t = Array.isArray(propSchema.type) ? 'string' : propSchema.type;

  switch (t) {
    case 'string':
      return isRequired ? 'string' : 'string?';
    case 'boolean':
      return isRequired ? 'bool' : 'bool?';
    case 'number':
      return isRequired ? 'double' : 'double?';
    case 'integer':
      return isRequired ? 'int' : 'int?';
    case 'array': {
      const items = propSchema.items;
      const inner = mapType(items, true);
      const listType = `IReadOnlyList<${inner}>`;
      return isRequired ? listType : listType + '?';
    }
    case 'object': {
      // A map of display strings is read as one; any other object stays opaque.
      const values = propSchema.additionalProperties;
      if (!propSchema.properties && values && typeof values === 'object' && values.type === 'string') {
        const dictionary = 'IReadOnlyDictionary<string, string>';
        return isRequired ? dictionary : dictionary + '?';
      }
      return opaque(isRequired);
    }
    default:
      return opaque(isRequired);
  }
}

/**
 * Generate a C# record declaration from a schema object.
 *
 * @param {string} className - C# class name.
 * @param {object} schema - JSON Schema object (properties + required).
 * @param {string} summary - One-line XML doc summary.
 */
const DOC_REPLACEMENTS = [
  [/\bSchemeEngine\.process\(\)\s*\/\s*SchemeEngine\.validate\(\)/g, 'the scheme processing operation'],
  [/\bGuideEngine\.evaluate\(\)/g, 'the guide evaluation operation'],
  [/\bAccessEngine\.check\(\)/g, 'the access-check operation'],
];

function neutralizeDocText(summary) {
  let text = summary;
  for (const [pattern, replacement] of DOC_REPLACEMENTS) {
    text = text.replace(pattern, replacement);
  }
  return text;
}

/**
 * Names in member descriptions that belong to the TypeScript engine or the
 * scheme document model rather than to anything a .NET caller holds, replaced
 * by what they mean on the wire.
 */
const MEMBER_DOC_REPLACEMENTS = [
  [/`SchemeEngine\.collectNotices\(\)`/g, 'the notices operation'],
  [/`RenderConfigDoc\.surfaces`/g, "the scheme's `render.surfaces`"],
];

/** Escape text for an XML doc comment. */
function escapeXmlDoc(text) {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

/**
 * XML doc text for one generated member: the first paragraph of the
 * property's description in the contract, or null when the contract gives
 * none. The later paragraphs carry detail the contract's own reference states
 * in full; the first is what a caller needs at the point of use. Markdown code
 * spans and JSDoc links become <c> elements.
 *
 * @param {string | undefined} description - The property's schema description.
 * @returns {string | null}
 */
function memberDocText(description) {
  if (typeof description !== 'string' || description.trim() === '') return null;
  let text = description.split(/\n\s*\n/)[0].replace(/\s+/g, ' ').trim();
  for (const [pattern, replacement] of MEMBER_DOC_REPLACEMENTS) {
    text = text.replace(pattern, replacement);
  }
  text = neutralizeDocText(text);
  text = escapeXmlDoc(text);
  text = text.replace(/\s*\{@link\s+([^\s}]+)\s*\}\s*/g, ' <c>$1</c> ');
  text = text.replace(/`([^`]+)`/g, '<c>$1</c>');
  return text.replace(/<\/c> ([.,:;])/g, '</c>$1').replace(/ {2,}/g, ' ').trim();
}

function generateRecord(className, schema, summary) {
  const props = schema.properties || {};
  const required = new Set(schema.required || []);

  const requiredFields = []; // required on the wire → no default
  const optionalFields = []; // non-required fields → default null

  for (const [jsonName, propSchema] of Object.entries(props)) {
    const isReq = required.has(jsonName);
    const csName = toPascalCase(jsonName);
    const csType = mapType(propSchema, isReq, className + '.' + jsonName);
    const doc = memberDocText(propSchema?.description);
    if (isReq) requiredFields.push({ csName, csType, hasDefault: false, doc });
    else optionalFields.push({ csName, csType, hasDefault: true, doc });
  }

  // C# record: required params first, then optional params with defaults
  const allFields = [...requiredFields, ...optionalFields];
  const lines = [];
  const docSummary = neutralizeDocText(summary);

  lines.push(`/// <summary>${docSummary}</summary>`);
  // A positional record's <param> text is also its property's IntelliSense.
  for (const { csName, doc } of allFields) {
    if (doc) lines.push(`/// <param name="${csName}">${doc}</param>`);
  }
  lines.push(`public record ${className}(`);

  allFields.forEach(({ csName, csType, hasDefault }, i) => {
    const defaultVal = hasDefault ? ' = null' : '';
    const comma = i < allFields.length - 1 ? ',' : '';
    lines.push(`    ${csType} ${csName}${defaultVal}${comma}`);
  });

  lines.push(');');
  return lines.join('\n');
}

/** Read a JSON Schema file. Returns null if missing. */
function readSchema(filename) {
  const p = path.join(schemasDir, filename);
  if (!fs.existsSync(p)) return null;
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

