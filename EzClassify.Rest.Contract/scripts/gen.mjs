/**
 * Read the `components.schemas` section of the vendored OpenAPI document.
 *
 * The document is written by one emitter in one YAML style: block mappings and
 * sequences, plain and double-quoted scalars, folded and literal block scalars,
 * and `[]`/`{}` for an empty collection. This reads that style and refuses
 * anything else, so a change in how the contract is written stops generation
 * instead of quietly reading it wrong. The generator stays free of a parser
 * dependency.
 *
 * @param {string} text - The OpenAPI document.
 * @returns {Record<string, object>} The component schemas by name.
 */
function readComponentSchemas(text) {
  const lines = text.split('\n');
  const start = lines.indexOf('  schemas:');
  if (start < 0) throw new Error('OpenAPI document has no components.schemas section');
  let end = start + 1;
  while (end < lines.length && (lines[end] === '' || lines[end].startsWith('    '))) end++;
  const body = lines.slice(start + 1, end);
  let i = 0;
  const indentOf = (line) => line.length - line.trimStart().length;
  const skipBlank = () => { while (i < body.length && body[i].trim() === '') i++; };

  function scalar(raw, indent) {
    if (raw === '>' || raw === '>-' || raw === '|' || raw === '|-') {
      const folded = raw.startsWith('>');
      const block = [];
      while (i < body.length && (body[i].trim() === '' || indentOf(body[i]) > indent)) {
        block.push(body[i].trim());
        i++;
      }
      while (block.length && block[block.length - 1] === '') block.pop();
      if (!folded) return block.join('\n');
      return block.join('\n').split(/\n{2,}/).map((p) => p.replace(/\n/g, ' ')).join('\n\n');
    }
    if (raw === '[]') return [];
    if (raw === '{}') return {};
    if (raw.startsWith('"')) return JSON.parse(raw);
    if (/^['&*!|>{[]/.test(raw)) throw new Error(`Unsupported OpenAPI YAML scalar: ${raw}`);
    return raw;
  }

  function node(indent) {
    skipBlank();
    if (i >= body.length || indentOf(body[i]) < indent) return null;
    if (body[i].slice(indent).startsWith('- ')) {
      const items = [];
      while (i < body.length && indentOf(body[i]) === indent && body[i].slice(indent).startsWith('- ')) {
        const rest = body[i].slice(indent + 2);
        if (/^[^"\s][^:]*:( |$)/.test(rest)) {
          // A mapping item: its first key sits on the dash line.
          body[i] = ' '.repeat(indent + 2) + rest;
          items.push(mapping(indent + 2));
        } else {
          i++;
          items.push(scalar(rest.trim(), indent));
        }
        skipBlank();
      }
      return items;
    }
    return mapping(indent);
  }

  function mapping(indent) {
    const out = {};
    while (i < body.length) {
      skipBlank();
      if (i >= body.length || indentOf(body[i]) !== indent) break;
      const line = body[i].slice(indent);
      const match = /^("(?:[^"\\]|\\.)*"|[^:]+):(?: (.*))?$/.exec(line);
      if (!match) throw new Error(`Unsupported OpenAPI YAML line: ${body[i]}`);
      const key = match[1].startsWith('"') ? JSON.parse(match[1]) : match[1];
      i++;
      out[key] = match[2] === undefined ? node(indent + 2) : scalar(match[2], indent);
    }
    return out;
  }

  return mapping(4);
}

/**
 * Template records that wear a different name than the contract component they
 * carry, as `Component` or `Component/property` paths. A property path ending
 * in `[]` names the items of an array property.
 */
const TEMPLATE_COMPONENT_ALIASES = {
  AuditPart: 'DocumentPartAssessment',
  AuditWhole: 'DocumentWholeOccurrence',
  ConceptRef: 'FixConceptReference',
  CoverageReport: 'CheckCoverageResult',
  FilterCount: 'FilterResult/total',
  GuideView: 'GuideViewResponse',
  GuideViewCategory: 'GuideViewResponse/categories[]',
  SchemeContextFormats: 'SchemeSummary/contextFormats',
  SchemeView: 'SchemeViewResponse',
  SchemeViewCategory: 'SchemeViewResponse/categories[]',
  UnmarkedSpan: 'DocumentUnmarkedSpan',
};

/** The property descriptions a component declares, its union variants' included. */
function componentPropertyDocs(schemas, record) {
  const [component, ...trail] = (TEMPLATE_COMPONENT_ALIASES[record] ?? record).split('/');
  const resolve = (schema) => (schema?.$ref ? schemas[schema.$ref.split('/').at(-1)] : schema);
  let schema = schemas[component];
  for (const step of trail) {
    const property = resolve(schema)?.properties?.[step.replace(/\[\]$/, '')];
    schema = step.endsWith('[]') ? property?.items : property;
  }
  schema = resolve(schema);
  if (!schema) return null;
  const docs = new Map();
  for (const variant of [schema, ...(schema.anyOf ?? schema.oneOf ?? []).map(resolve)]) {
    for (const [name, property] of Object.entries(variant?.properties ?? {})) {
      const doc = memberDocText(property?.description);
      if (doc && !docs.has(toPascalCase(name))) docs.set(toPascalCase(name), doc);
    }
  }
  return docs;
}

/** The parameter names of a positional record, from the text after its opening parenthesis. */
function recordParameterNames(text) {
  let depth = 0;
  let current = '';
  const params = [];
  for (const char of text) {
    if (char === '(' || char === '<' || char === '[') depth++;
    if (char === ')' && depth === 0) break;
    if (char === ')' || char === '>' || char === ']') depth--;
    if (char === ',' && depth === 0) {
      params.push(current);
      current = '';
    } else current += char;
  }
  params.push(current);
  return params
    .map((param) => param.replace(/\[[^\]]*\]/g, '').split('=')[0].trim().split(/\s+/).at(-1))
    .filter(Boolean);
}

/**
 * Give every positional record in a template the contract's description of each
 * parameter it leaves undocumented, as a `<param>` in its doc comment, so the
 * template records document their members the way the generated ones do. A
 * hand-written `<param>` is kept. A record is left alone unless the contract
 * describes every parameter it lacks, because a partly documented record is a
 * CS1573 warning.
 */
function describeTemplateRecords(template, schemas) {
  const lines = template.split('\n');
  for (let index = lines.length - 1; index >= 0; index--) {
    const match = /^public (?:(?:sealed|abstract|partial) )*record (\w+)\(/.exec(lines[index]);
    if (!match) continue;
    const docs = componentPropertyDocs(schemas, match[1]);
    if (!docs) continue;
    let docStart = index;
    while (docStart > 0 && lines[docStart - 1].startsWith('///')) docStart--;
    const existing = new Set(
      [...lines.slice(docStart, index).join('\n').matchAll(/<param name="(\w+)">/g)].map((m) => m[1]),
    );
    const rest = [lines[index].slice(match[0].length), ...lines.slice(index + 1)].join('\n');
    const missing = recordParameterNames(rest).filter((name) => !existing.has(name));
    if (!missing.length || !missing.every((name) => docs.has(name))) continue;
    lines.splice(index, 0, ...missing.map((name) => `/// <param name="${name}">${docs.get(name)}</param>`));
  }
  return lines.join('\n');
}

/**
 * The component schemas every 2xx response body of the contract names, read
 * from the operation list: `$ref`s under a `"2xx":` response, whether the body
 * is the schema itself or the items of an array. The same document styles the
 * component reader accepts; an operation whose success response names no
 * component stops generation rather than going unchecked.
 */
function readResponseRoots(text) {
  const lines = text.split('\n');
  const start = lines.indexOf('paths:');
  if (start < 0) throw new Error('OpenAPI document has no paths section');
  const roots = new Set();
  let operation = null;
  let responseIndent = -1;
  let sawRef = true;
  const closeResponse = () => {
    if (!sawRef) throw new Error(`2xx response of ${operation} names no component schema`);
    responseIndent = -1;
  };
  for (let i = start + 1; i < lines.length; i++) {
    const line = lines[i];
    if (line.trim() === '') continue;
    const indent = line.length - line.trimStart().length;
    if (indent === 0) break;
    if (responseIndent >= 0 && indent <= responseIndent) closeResponse();
    const route = /^ {2}(\/\S*):$/.exec(line);
    if (route) operation = route[1];
    if (/^ {4}(get|post|put|patch|delete):$/.test(line)) operation = `${operation.split(' ')[0]} ${line.trim().slice(0, -1)}`;
    if (/^ {8}"2\d\d":$/.test(line)) {
      responseIndent = indent;
      sawRef = false;
      continue;
    }
    if (responseIndent >= 0) {
      const ref = /\$ref: "#\/components\/schemas\/(\w+)"/.exec(line);
      if (ref) {
        roots.add(ref[1]);
        sawRef = true;
      }
    }
  }
  if (responseIndent >= 0) closeResponse();
  return [...roots].sort();
}

/**
 * The shape of a schema as far as response checking needs it: the container
 * kind a value must have and the members an object requires, down through
 * references. Scalars and opaque payloads have no shape (null); the checker
 * judges only presence, and the parsers judge the value.
 */
function responseShape(schemas, schema) {
  if (!schema || typeof schema !== 'object') return null;
  if (schema.$ref) {
    const name = schema.$ref.split('/').at(-1);
    if (!schemas[name]) throw new Error(`OpenAPI reference to missing component: ${name}`);
    return isScalarSchema(schemas, schemas[name], new Set()) ? null : { ref: name };
  }
  if (schema.allOf) throw new Error('allOf is not supported by the response shape generator');
  const alternatives = schema.anyOf ?? schema.oneOf;
  if (alternatives) {
    const objects = [];
    let scalar = false;
    for (const alternative of alternatives) {
      if (alternative.type === 'null') continue;
      const shape = responseShape(schemas, alternative);
      if (shape === null) scalar = true;
      else objects.push({ shape, consts: constMembers(schemas, alternative) });
    }
    return objects.length === 0 ? null : { any: objects, scalar };
  }
  const types = [].concat(schema.type ?? []);
  if (types.includes('array')) return { arr: responseShape(schemas, schema.items) };
  if (types.includes('object') || schema.properties) {
    const members = Object.entries(schema.properties ?? {})
      .map(([name, property]) => [name, responseShape(schemas, property)])
      .filter(([, shape]) => shape !== null);
    const additional = typeof schema.additionalProperties === 'object'
      ? responseShape(schemas, schema.additionalProperties)
      : null;
    const required = schema.required ?? [];
    if (isScalarSchema(schemas, schema, new Set())) return null;
    if (additional !== null && !schema.properties) return { map: additional };
    if (additional !== null) throw new Error('A schema with both properties and structured additionalProperties is not supported by the response shape generator');
    return {
      obj: {
        required,
        nullable: required.filter((name) => isNullable(schemas, schema.properties?.[name])),
        members,
      },
    };
  }
  return null;
}

/** Whether a schema carries no container: a string, number, boolean, enum or opaque payload. */
function isScalarSchema(schemas, schema, seen) {
  if (!schema || typeof schema !== 'object') return true;
  if (schema.$ref) {
    const name = schema.$ref.split('/').at(-1);
    if (seen.has(name)) return true;
    seen.add(name);
    return isScalarSchema(schemas, schemas[name], seen);
  }
  const alternatives = schema.anyOf ?? schema.oneOf;
  if (alternatives) return alternatives.every((alternative) => isScalarSchema(schemas, alternative, seen));
  const types = [].concat(schema.type ?? []);
  if (types.includes('array')) return false;
  if (types.includes('object') || schema.properties) {
    return !schema.required?.length && !Object.keys(schema.properties ?? {}).length
      && (typeof schema.additionalProperties !== 'object'
        || isScalarSchema(schemas, schema.additionalProperties, seen));
  }
  return true;
}

/** The discriminating `const` members of a union alternative, by property name. */
function constMembers(schemas, alternative) {
  const resolved = alternative.$ref ? schemas[alternative.$ref.split('/').at(-1)] : alternative;
  return Object.entries(resolved?.properties ?? {})
    .filter(([, property]) => typeof property?.const === 'string')
    .map(([name, property]) => [name, property.const]);
}

/** Whether a schema admits JSON null as a value of its own. */
function isNullable(schemas, schema) {
  if (!schema) return false;
  if (schema.$ref) return isNullable(schemas, schemas[schema.$ref.split('/').at(-1)]);
  if ([].concat(schema.type ?? []).includes('null')) return true;
  return (schema.anyOf ?? schema.oneOf ?? []).some((alternative) => isNullable(schemas, alternative));
}

const csString = (value) => JSON.stringify(value);

function shapeSource(shape) {
  if (shape.ref) return `ShapeNode.Ref(${csString(shape.ref)})`;
  if (shape.arr !== undefined) return `ShapeNode.Arr(${shape.arr === null ? 'null' : shapeSource(shape.arr)})`;
  if (shape.map) return `ShapeNode.Map(${shapeSource(shape.map)})`;
  if (shape.any) {
    const alternatives = shape.any.map(({ shape: alternative, consts }) =>
      `(${shapeSource(alternative)}, ${consts.length ? `new[] { ${consts.map(([name, value]) => `(${csString(name)}, ${csString(value)})`).join(', ')} }` : 'null'})`);
    return `ShapeNode.Any(${shape.scalar}, ${alternatives.join(', ')})`;
  }
  const { required, nullable, members } = shape.obj;
  const parts = [`required: ${csString(required.join(' '))}`];
  if (nullable.length) parts.push(`nullable: ${csString(nullable.join(' '))}`);
  if (members.length) {
    parts.push(`members: new[] { ${members.map(([name, member]) => `(${csString(name)}, ${shapeSource(member)})`).join(', ')} }`);
  }
  return `ShapeNode.Obj(${parts.join(', ')})`;
}

/**
 * The generated table of response shapes: for every component schema reachable
 * from a success response, the members it requires and the containers it
 * holds. `ResponseCheck` walks it so a body missing a member the contract
 * requires, at any depth, is refused before a parser reads it. The table is
 * derived from the `required` lists and nothing else; no schema or member is
 * named by hand.
 */
function emitResponseShapes(schemas) {
  const reachable = new Set();
  const visit = (schema) => {
    if (!schema || typeof schema !== 'object') return;
    if (schema.$ref) {
      const name = schema.$ref.split('/').at(-1);
      if (reachable.has(name)) return;
      reachable.add(name);
      visit(schemas[name]);
      return;
    }
    for (const property of Object.values(schema.properties ?? {})) visit(property);
    visit(schema.items);
    if (typeof schema.additionalProperties === 'object') visit(schema.additionalProperties);
    for (const alternative of [...(schema.anyOf ?? []), ...(schema.oneOf ?? []), ...(schema.allOf ?? [])]) visit(alternative);
  };
  for (const root of readResponseRoots(openapiText)) visit({ $ref: `#/components/schemas/${root}` });
  const entries = [...reachable].sort().flatMap((name) => {
    const shape = responseShape(schemas, schemas[name]);
    return shape === null ? [] : [`        [${csString(name)}] = ${shapeSource(shape)},`];
  });
  return `
/// <summary>
/// The shape of every component schema a success response can carry, generated
/// from the contract's <c>required</c> lists. <see cref="ResponseCheck"/> reads it.
/// </summary>
internal static class ResponseShapes
{
    internal static readonly IReadOnlyDictionary<string, ShapeNode> Components = new Dictionary<string, ShapeNode>
    {
${entries.join('\n')}
    };
}
`;
}

